<?php

namespace Database\Seeders\Support;

/**
 * The six static pages, written rather than generated.
 *
 * They used to be `BanglaContent::paragraph()` — the same Markov-ish filler
 * the article factory uses — which is right for 374 articles nobody reads and
 * wrong for the six pages a reader opens *because* they want to know
 * something. "আমাদের সম্পর্কে" full of sentence-shaped noise is the single
 * clearest sign an installation is not finished.
 *
 * This is a **demonstration** newspaper, and the copy says so wherever a
 * reader might otherwise assume an organisation stands behind it. Nothing
 * here invents an address, a phone number, a company or an editor: those are
 * legal details on a real masthead, and a plausible-looking fake is worse than
 * an obvious blank because it does not get corrected.
 *
 * Markup is limited to what `App\Support\Html::ALLOWED` keeps — `p`, `h2`,
 * `ul`/`li`, `strong`, `a`. Anything else is stripped on write by the model's
 * `saving()` hook, silently, so it is not worth reaching for.
 */
final class StaticPageContent
{
