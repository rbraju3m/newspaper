    public static function all(): array
    {
        return [
            'about' => self::about(),
            'contact' => self::contact(),
            'advertise' => self::advertise(),
            'privacy' => self::privacy(),
            'terms' => self::terms(),
            'comment-policy' => self::commentPolicy(),
        ];
    }

