    public static function headline(?string $categorySlug = null): string
    {
        $pool = self::HEADLINES[$categorySlug] ?? null;

        // 60% from the category pool when one exists, so headlines read as if
        // they belong to their section without every story being a duplicate.
        if ($pool && random_int(1, 100) <= 60) {
            return $pool[array_rand($pool)];
        }

        return self::TOPICS_PHRASES[array_rand(self::TOPICS_PHRASES)].' '
            .self::SUBJECTS[array_rand(self::SUBJECTS)].' '
            .self::PREDICATES[array_rand(self::PREDICATES)];
    }

    public static function sentence(int $words = 12): string
    {
        $picked = [];
        for ($i = 0; $i < $words; $i++) {
            $picked[] = self::PARAGRAPH_WORDS[array_rand(self::PARAGRAPH_WORDS)];
        }

        return implode(' ', $picked).'।';
    }

    public static function paragraph(int $sentences = 4): string
    {
        return implode(' ', array_map(
            fn () => self::sentence(random_int(8, 18)),
            range(1, $sentences),
        ));
    }

    /** An HTML body with paragraphs, a pull quote and a subheading. */
    public static function body(int $paragraphs = 8): string
    {
        $html = [];

        foreach (range(1, $paragraphs) as $i) {
            $html[] = '<p>'.self::paragraph(random_int(3, 5)).'</p>';

            if ($i === 3) {
                $html[] = '<h2>'.self::TOPICS_PHRASES[array_rand(self::TOPICS_PHRASES)].'</h2>';
            }

            if ($i === 5) {
                $html[] = '<blockquote><p>'.self::sentence(14).'</p></blockquote>';
            }
        }

        return implode("\n", $html);
    }

    public static function excerpt(): string
    {
        return self::sentence(random_int(14, 22));
    }

    public static function dateline(): string
    {
        return self::DATELINES[array_rand(self::DATELINES)];
